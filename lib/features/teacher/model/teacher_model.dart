class StaffModel {
  final String id;
  final String name;
  final String designation;
  final String employeeId;
  final String email;
  final String phone;
  final String imageUrl;

  StaffModel({
    required this.id,
    required this.name,
    required this.designation,
    required this.employeeId,
    required this.email,
    required this.phone,
    required this.imageUrl,
  });
}